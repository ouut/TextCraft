    /// Render composite snapshot for an online player `(engine:render-snapshot pid)`.
    pub fn render_snapshot(&mut self, pid: u64) -> Result<PlayerSnapshot, String> {
        let args = vec![SteelVal::IntV(pid as isize)];
        let val = self
            .app
            .safe_call_function("engine:render-snapshot", args, 500)
            .map_err(|e| format!("engine:render-snapshot error: {}", e))?;

        let mut snapshot = if let SteelVal::HashMapV(ref hm) = val {
            let k_cols = SteelVal::StringV("cols".into());
            let k_rows = SteelVal::StringV("rows".into());
            let k_screen = SteelVal::StringV("screen".into());
            let k_hud = SteelVal::StringV("hud".into());

            if let (
                Some(SteelVal::IntV(cols)),
                Some(SteelVal::IntV(rows)),
                Some(SteelVal::StringV(screen)),
                Some(hud_val),
            ) = (
                hm.get(&k_cols),
                hm.get(&k_rows),
                hm.get(&k_screen),
                hm.get(&k_hud),
            ) {
                let hud = steel_val_to_json(hud_val)
                    .map_err(|e| format!("steel_val_to_json error: {}", e))?;
                PlayerSnapshot {
                    cols: *cols as u16,
                    rows: *rows as u16,
                    screen: screen.to_string(),
                    hud,
                }
            } else {
                let json = steel_val_to_json(&val)
                    .map_err(|e| format!("steel_val_to_json error: {}", e))?;
                serde_json::from_value(json)
                    .map_err(|e| format!("Failed to parse PlayerSnapshot: {}", e))?
            }
        } else {
            let json = steel_val_to_json(&val)
                .map_err(|e| format!("steel_val_to_json error: {}", e))?;
            serde_json::from_value(json)
                .map_err(|e| format!("Failed to parse PlayerSnapshot: {}", e))?
        };

        // If Flecs ECS spatial grid is populated, take advantage of native ViewportRasterizer
        let ecs = self.ecs_world.lock();
        if !ecs.is_empty() {
            let mut center_pos = None;
            let query = ecs.world.query::<(&PlayerSession, &GridPos)>().build();
            query.each(|(session, pos)| {
                if session.player_id == pid {
                    center_pos = Some((pos.x, pos.y));
                }
            });

            if center_pos.is_none() {
                if let (Some(x), Some(y)) = (
                    snapshot.hud.get("player").and_then(|p| p.get("x")).and_then(|v| v.as_i64()),
                    snapshot.hud.get("player").and_then(|p| p.get("y")).and_then(|v| v.as_i64()),
                ) {
                    center_pos = Some((x as i32, y as i32));
                }
            }

            if let Some((cx, cy)) = center_pos {
                let is_dw = snapshot.hud.get("double_width").and_then(|v| v.as_bool()).unwrap_or(false);
                let screen = self.rasterizer.lock().render(&ecs, cx, cy, snapshot.cols, snapshot.rows, is_dw).to_string();
                snapshot.screen = screen;
            }
        }

        Ok(snapshot)
    }

