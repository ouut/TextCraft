    /// Atomically save world state to disk using `.tmp` and rename.
    pub fn save_state_to_file(&mut self) -> Result<(), Box<dyn std::error::Error>> {
        let save_path = match &self.save_file {
            Some(p) => p.clone(),
            None => return Ok(()),
        };

        let state = self
            .export_state()
            .map_err(std::io::Error::other)?;

        if let Some(parent) = save_path.parent() {
            if !parent.as_os_str().is_empty() {
                std::fs::create_dir_all(parent)?;
            }
        }

        let tmp_path = save_path.with_extension(format!(
            "{}.tmp",
            save_path
                .extension()
                .and_then(|s| s.to_str())
                .unwrap_or("json")
        ));

        let content = serde_json::to_string_pretty(&state)?;
        std::fs::write(&tmp_path, content)?;
        std::fs::rename(&tmp_path, &save_path)?;

        tracing::debug!(path = %save_path.display(), "Game state atomically saved");
        Ok(())
    }

    /// Load world state from save file on disk.
    pub fn load_state_from_file(&mut self) -> Result<bool, Box<dyn std::error::Error>> {
        let save_path = match &self.save_file {
            Some(p) => p.clone(),
            None => return Ok(false),
        };

        if !save_path.exists() {
            return Ok(false);
        }

        let content = std::fs::read_to_string(&save_path)?;
        let json: Value = serde_json::from_str(&content)?;
        self.import_state(&json)
            .map_err(std::io::Error::other)?;

        tracing::debug!(path = %save_path.display(), "Game state loaded from save file");
        Ok(true)
    }

    /// Force immediate reload of all root `.scm` scripts in `scripts_dir`.
    ///
    /// If `clean` is true, previous world state is discarded and `(engine:on-init)`
    /// is invoked to initialize a fresh world.
    /// If `clean` is false, previous world state is preserved and restored.
    /// In either case, if compilation fails, the previous world state is safely restored.
    pub fn force_reload(&mut self, clean: bool) -> Result<(), String> {
        tracing::info!(
            scripts_dir = %self.scripts_dir.display(),
            clean,
            "Forcing immediate reload of Scheme scripts..."
        );
        let state = self.export_state().ok();

        let entries = std::fs::read_dir(&self.scripts_dir)
            .map_err(|e| format!("Failed to read scripts directory: {}", e))?;
        let mut files: Vec<PathBuf> = entries
            .filter_map(|e| e.ok().map(|entry| entry.path()))
            .filter(|f| f.is_file() && f.extension().is_some_and(|ext| ext == "scm"))
            .collect();
        sort_script_files(&mut files);

        // Read all target files first before running any compilation
        let mut sources = Vec::with_capacity(files.len());
        for file in files {
            let code = std::fs::read_to_string(&file)
                .map_err(|e| format!("Failed to read {}: {}", file.display(), e))?;
            sources.push((file, code));
        }

        for (file, code) in sources {
            if let Err(e) = self
                .app
                .engine
                .compile_and_run_raw_program_with_path(code, file.clone())
            {
                tracing::warn!(
                    file = %file.display(),
                    error = %e,
                    "Failed to compile script during reload, restoring state"
                );
                if let Some(st) = state {
                    let _ = self.import_state(&st);
                }
                return Err(format!("Failed to compile {}: {}", file.display(), e));
            }
        }

        if clean {
            if let Err(e) = self.app.call_function("engine:on-init", vec![]) {
                tracing::warn!(
                    error = %e,
                    "Failed to run engine:on-init during clean reload, restoring state"
                );
                if let Some(st) = state {
                    let _ = self.import_state(&st);
                }
                return Err(format!("Failed to run engine:on-init during clean reload: {}", e));
            }
        } else if let Some(st) = state {
            let _ = self.import_state(&st);
        }

        if let Some(ref mut watcher) = self.watcher {
            let _ = watcher.check_modified();
        }
        self.extra_version = self.extra_version.wrapping_add(1);

        if clean {
            tracing::info!("Scripts reloaded successfully with clean initial state");
        } else {
            tracing::info!("Scripts reloaded successfully with state preserved");
        }
        Ok(())
    }

    /// Check if watched `.scm` script files have been modified and reload with state preservation.
    pub fn check_reload(&mut self) -> Result<bool, Box<dyn std::error::Error>> {
        let is_modified = if let Some(ref mut watcher) = self.watcher {
            tracing::trace!(
                scripts_dir = %self.scripts_dir.display(),
                "Checking scripts directory for modifications"
            );
            watcher.check_modified()
        } else {
            return Ok(false);
        };

        if is_modified {
            tracing::info!("Script changes detected, reloading scripts...");
            self.force_reload(false)
                .map_err(|e| Box::new(std::io::Error::other(e)))?;
            return Ok(true);
        }
        Ok(false)
    }

