    /// Query current target FPS from Scheme (clamped 1..=60, default 60).
    pub fn query_target_fps(&mut self) -> u64 {
        match self.app.call_function("engine:target-fps", vec![]) {
            Ok(SteelVal::IntV(n)) => (n as u64).clamp(1, 60),
            Ok(SteelVal::NumV(f)) => (f as u64).clamp(1, 60),
            _ => 60,
        }
    }

    /// Advance game tick `(engine:on-tick dt tick-id)`.
    pub fn on_tick(&mut self, dt: f32, tick_id: u64) -> Result<(), String> {
        self.ecs_world.lock().progress(dt);
        let args = vec![
            SteelVal::NumV(dt as f64),
            SteelVal::IntV(tick_id as isize),
        ];
        self.app
            .safe_call_function("engine:on-tick", args, 500)
            .map_err(|e| format!("engine:on-tick error: {}", e))?;
        Ok(())
    }

